# Assignment statement
num = 5

# Conditional statement
if num > 0:
    print("Positive Number")

# Loop statement
for i in range(3):
    print(i)

# Print statement
print("Program Finished")

# Output:
# Positive Number
# 0
# 1
# 2
# Program Finished


# Using line continuation (\)
total = 10 + 20 + \
        30 + 40
print(total)

# Using parentheses ()
sum1 = (10 + 20 +
        30 + 40)
print(sum1)

# Output:
# 100
# 100



a = 5; b = 10; print(a + b)

# Output:
# 15
