# 1. Store first name and last name
first_name = "Jyothirmayee"
last_name = "Kumarapu"

# 2. Concatenate them into a full name
full_name = first_name + " " + last_name

# 3. Print the full name in different cases
print("Full Name:", full_name)
print("UPPERCASE:", full_name.upper())
print("lowercase:", full_name.lower())
print("Title Case:", full_name.title())

# 4. Print the length of the full name
print("Length of Full Name:", len(full_name))

# 5. Print the first and last character of the full name
print("First Character:", full_name[0])
print("Last Character:", full_name[-1])
#output
#Full Name: Jyothirmayee Kumarapu
#UPPERCASE: JYOTHIRMAYEE KUMARAPU
#lowercase: jyothirmayee kumarapu
#Title Case: Jyothirmayee Kumarapu
#Length of Full Name: 22
#First Character: J
#Last Character: u







# 1. Declare two boolean variables
